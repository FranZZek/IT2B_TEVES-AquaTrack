package com.aquatrack.ui;

import com.aquatrack.dao.ActivityLogDao;
import com.aquatrack.dao.PoolLogDao;
import com.aquatrack.model.ActivityLog;
import com.aquatrack.model.DailyReport;
import com.aquatrack.model.UnitUsage;
import com.aquatrack.model.User;

import java.nio.file.Path;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.List;
import java.util.Scanner;

/**
 * "Daily Pool Usage & Guest Report" screen, shared by the Building Admin and the Billing Clerk.
 * Pick a date, see residents vs guests per unit with a totals row, then export it to CSV or PDF.
 * It only reads data (PoolLogDao.getDailyReport) and writes one audit entry when a file is saved.
 * Both exports get the SAME DailyReport object as the screen, so the numbers always match.
 * There is no SQL in here.
 */
public class ReportMenu {

    private final User user;
    private final PoolLogDao poolLogDao;         // the ONE shared DAOs created in Main
    private final ActivityLogDao activityLogDao;
    private final Scanner scanner;               // the ONE shared Scanner created in Main
    private final String accent;                 // the color of the role that opened this screen

    public ReportMenu(User user, PoolLogDao poolLogDao, ActivityLogDao activityLogDao,
                      Scanner scanner, String accent) {
        this.user = user;
        this.poolLogDao = poolLogDao;
        this.activityLogDao = activityLogDao;
        this.scanner = scanner;
        this.accent = accent;
    }

    // Asks for a date, shows its report, and repeats until the user goes back.
    public void start() {
        Theme.clearScreen();
        LocalDate date = askDate();

        while (date != null) {
            Theme.loading("Generating report");
            DailyReport report = poolLogDao.getDailyReport(date.toString());
            date = showReport(report); // another date, or null when the user goes back
        }
    }

    // ------------------------------------------------------------- screens

    // Draws the report and its option menu. Returns the next date to report on, or null for "Back".
    private LocalDate showReport(DailyReport report) {
        while (true) {
            Theme.clearScreen();
            printReport(report);
            Theme.menu("REPORT OPTIONS", accent, List.of(),
                    "Export to CSV",
                    "Export to PDF",
                    "Choose Another Date",
                    "Back");

            int choice = InputHelper.readInt(scanner, "Choose an option: ", 1, 4);

            switch (choice) {
                case 1 -> { exportCsv(report); Theme.pause(scanner); }
                case 2 -> { exportPdf(report); Theme.pause(scanner); }
                case 3 -> {
                    LocalDate another = askDate();
                    if (another != null) {
                        return another;
                    }
                }
                case 4 -> {
                    return null;
                }
            }
        }
    }

    // Residents vs guests per unit, a totals row, and a short summary. Entering 0 at the date prompt cancels.
    private void printReport(DailyReport report) {
        Theme.heading("Daily Pool Usage & Guest Report");
        Theme.info("Date: " + report.date() + "    Generated by: " + user.fullName() + " (" + user.role() + ")");

        if (report.isEmpty()) {
            Theme.warn("No pool activity was recorded on " + report.date() + ".");
            return;
        }

        List<String[]> rows = new ArrayList<>();
        for (UnitUsage row : report.rows()) {
            rows.add(new String[]{
                    String.valueOf(row.unitNumber()),
                    row.ownerName(),
                    String.valueOf(row.checkIns()),
                    String.valueOf(row.residents()),
                    String.valueOf(row.guests()),
                    String.valueOf(row.total())
            });
        }
        String[] totals = {
                Theme.bold("TOTAL"),
                "",
                Theme.bold(String.valueOf(report.totalCheckIns())),
                Theme.bold(String.valueOf(report.totalResidents())),
                Theme.bold(String.valueOf(report.totalGuests())),
                Theme.bold(String.valueOf(report.totalSwimmers()))
        };
        Theme.table(new String[]{"Unit", "Owner", "Check-ins", "Residents", "Guests", "Total Swimmers"},
                rows, totals, "unit");

        // Math.round makes the two percentages add up to about 100. totalSwimmers is never 0 here,
        // because the database does not allow an empty group.
        int total = report.totalSwimmers();
        int guestPercent = (int) Math.round(report.totalGuests() * 100.0 / total);
        Theme.info("Swimmers: " + total + "  =  " + Theme.green(report.totalResidents() + " resident(s)")
                + " + " + Theme.yellow(report.totalGuests() + " guest(s)")
                + "   (guests: " + guestPercent + "%)");
        System.out.println(Theme.gray("A group counts on the day it checked in."));
    }

    // ------------------------------------------------------------- options

    // Saves the report as a CSV file in reports/. Nothing is saved for an empty day.
    private void exportCsv(DailyReport report) {
        if (nothingToExport(report)) {
            return;
        }

        Theme.loading("Exporting CSV");
        Path file = ReportExporter.exportDailyCsv(report, user);
        finishExport(report, file, "CSV");
    }

    // Saves the report as a PDF file in reports/. Nothing is saved for an empty day.
    private void exportPdf(DailyReport report) {
        if (nothingToExport(report)) {
            return;
        }

        Theme.loading("Exporting PDF");
        Path file = ReportExporter.exportDailyPdf(report, user);
        finishExport(report, file, "PDF");
    }

    // An empty day has no table to print, so both exports refuse it with the same message.
    private boolean nothingToExport(DailyReport report) {
        if (report.isEmpty()) {
            Theme.warn("There is nothing to export for " + report.date() + ".");
            return true;
        }
        return false;
    }

    // Shared by both exports: tells the user where the file is and writes the audit entry.
    // file is null when the exporter could not save it (it has already shown the reason).
    private void finishExport(DailyReport report, Path file, String format) {
        if (file != null) {
            Theme.success("Report saved to " + file.toAbsolutePath());
            activityLogDao.logAction(user.userId(), ActivityLog.REPORT_EXPORTED,
                    user.role() + " [" + user.userId() + "] exported the " + report.date()
                            + " daily report to " + format);
        } else {
            Theme.error("The report was NOT exported.");
        }
    }

    // Asks for the report date. Returns null if the user types 0.
    private LocalDate askDate() {
        return InputHelper.readDate(scanner,
                "Report date (yyyy-MM-dd, e.g. " + LocalDate.now() + "; 0 to cancel): ");
    }
}

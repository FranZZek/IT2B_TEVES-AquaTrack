package com.aquatrack.ui;

import com.aquatrack.model.DailyReport;
import com.aquatrack.model.UnitUsage;
import com.aquatrack.model.User;
import com.lowagie.text.Chunk;
import com.lowagie.text.Document;
import com.lowagie.text.DocumentException;
import com.lowagie.text.Element;
import com.lowagie.text.Font;
import com.lowagie.text.HeaderFooter;
import com.lowagie.text.PageSize;
import com.lowagie.text.Paragraph;
import com.lowagie.text.Phrase;
import com.lowagie.text.Rectangle;
import com.lowagie.text.pdf.PdfPCell;
import com.lowagie.text.pdf.PdfPTable;
import com.lowagie.text.pdf.PdfWriter;

import java.awt.Color;
import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.OutputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.ArrayList;
import java.util.List;

/**
 * Saves a report as a file inside the reports/ folder (next to aquatrack.db).
 * It gets a ready DailyReport, so there is no SQL in here and the numbers are the same as on the screen.
 * One method per format: exportDailyCsv (Part 6) and exportDailyPdf (Part 7, uses OpenPDF).
 */
public final class ReportExporter {

    // Created on the first export if it does not exist yet.
    private static final Path REPORTS_FOLDER = Path.of("reports");

    private static final DateTimeFormatter STAMP = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss");

    // ---- PDF look: the same water blues as the console theme ----

    private static final Color WATER_BLUE = new Color(0, 102, 153);
    private static final Color LIGHT_BLUE = new Color(220, 238, 247);   // totals row
    private static final Color STRIPE = new Color(245, 250, 253);       // every second table row
    private static final Color LINE_GRAY = new Color(190, 200, 205);    // table borders
    private static final Color TEXT_GRAY = new Color(100, 110, 115);

    // The base fonts that come with every PDF viewer, so nothing has to be installed or embedded.
    private static final Font BANNER_FONT = new Font(Font.HELVETICA, 22, Font.BOLD, Color.WHITE);
    private static final Font BANNER_SMALL_FONT = new Font(Font.HELVETICA, 10, Font.NORMAL, new Color(200, 230, 245));
    private static final Font TITLE_FONT = new Font(Font.HELVETICA, 16, Font.BOLD, WATER_BLUE);
    private static final Font LABEL_FONT = new Font(Font.HELVETICA, 10, Font.BOLD);
    private static final Font TEXT_FONT = new Font(Font.HELVETICA, 10, Font.NORMAL);
    private static final Font HEADER_FONT = new Font(Font.HELVETICA, 10, Font.BOLD, Color.WHITE);
    private static final Font SMALL_FONT = new Font(Font.HELVETICA, 8, Font.NORMAL, TEXT_GRAY);

    private static final String[] COLUMNS = {"Unit", "Owner", "Check-ins", "Residents", "Guests", "Total Swimmers"};

    // Relative widths of the six columns (the Owner column gets the most room).
    private static final float[] COLUMN_WIDTHS = {1f, 3.4f, 1.5f, 1.6f, 1.4f, 2f};

    private ReportExporter() {
        // Only static helpers: nothing to create.
    }

    // ------------------------------------------------------------------ CSV

    // Writes reports/daily-pool-report-yyyy-MM-dd.csv and returns its path, or null if it could not be saved.
    // The file name uses the REPORT date, so exporting the same day again replaces the old file
    // (the newer file has the newer numbers).
    public static Path exportDailyCsv(DailyReport report, User user) {
        List<String> lines = new ArrayList<>();

        // A few lines about the report first, then an empty line, then the table.
        lines.add("AquaTrack - Daily Pool Usage & Guest Report");
        lines.add("Report date," + report.date());
        lines.add("Generated by," + csv(user.fullName() + " (" + user.role() + ")"));
        lines.add("Generated at," + LocalDateTime.now().format(STAMP));
        lines.add("");

        lines.add("Unit,Owner,Check-ins,Residents,Guests,Total Swimmers");
        for (UnitUsage row : report.rows()) {
            lines.add(row.unitNumber() + "," + csv(row.ownerName()) + "," + row.checkIns() + ","
                    + row.residents() + "," + row.guests() + "," + row.total());
        }
        lines.add("TOTAL,," + report.totalCheckIns() + "," + report.totalResidents() + ","
                + report.totalGuests() + "," + report.totalSwimmers());

        Path file = reportFile(report, "csv");

        try {
            Files.createDirectories(REPORTS_FOLDER);
            Files.write(file, lines, StandardCharsets.UTF_8);
            return file;
        } catch (IOException e) {
            Theme.error("Could not save the file: " + e.getMessage());
            return null;
        }
    }

    // Makes one text safe for a CSV cell. A name like Santos, Maria would otherwise split into two columns,
    // so a text with a comma, a quote or a line break is wrapped in quotes (and inner quotes are doubled).
    private static String csv(String text) {
        if (text.contains(",") || text.contains("\"") || text.contains("\n")) {
            return "\"" + text.replace("\"", "\"\"") + "\"";
        }
        return text;
    }

    // ------------------------------------------------------------------ PDF

    // Writes reports/daily-pool-report-yyyy-MM-dd.pdf and returns its path, or null if it could not be saved.
    // Same file name rule as the CSV: exporting the same day again replaces the old file.
    public static Path exportDailyPdf(DailyReport report, User user) {
        Path file = reportFile(report, "pdf");

        try {
            // The PDF is built in memory first and written to disk only when it is complete.
            // So a failure half-way never leaves a broken file, and never destroys the previous good one.
            ByteArrayOutputStream buffer = new ByteArrayOutputStream();
            buildPdf(report, user, buffer);

            Files.createDirectories(REPORTS_FOLDER);
            Files.write(file, buffer.toByteArray());
            return file;
        } catch (IOException e) {
            // Most often the old PDF is still open in a viewer and Windows will not let us replace it.
            Theme.error("Could not save the file: " + e.getMessage() + " (is the old PDF still open?)");
            return null;
        } catch (DocumentException e) {
            Theme.error("Could not build the PDF: " + e.getMessage());
            return null;
        }
    }

    // Draws the whole page(s): banner, title and facts, the table, a short note. Page numbers go in the footer.
    private static void buildPdf(DailyReport report, User user, OutputStream out) throws DocumentException {
        Document document = new Document(PageSize.A4, 40, 40, 40, 50); // left, right, top, bottom margins
        PdfWriter.getInstance(document, out);

        // "Page 1", "Page 2"... A footer must be set BEFORE the document is opened.
        HeaderFooter footer = new HeaderFooter(new Phrase("AquaTrack Daily Pool Report   |   Page ", SMALL_FONT), true);
        footer.setAlignment(Element.ALIGN_CENTER);
        footer.setBorder(Rectangle.NO_BORDER); // no lines above and below the footer text
        document.setFooter(footer);

        document.open();
        document.add(banner());
        addHeading(document, report, user);
        document.add(usageTable(report));
        document.add(note());
        document.close();
    }

    // A blue band at the top (like the logo on the console): the app name and its tagline.
    private static PdfPTable banner() {
        PdfPCell cell = new PdfPCell();
        cell.addElement(new Paragraph("AquaTrack", BANNER_FONT));
        cell.addElement(new Paragraph("Condominium Pool Access & Guest Tracker", BANNER_SMALL_FONT));
        cell.setBackgroundColor(WATER_BLUE);
        cell.setBorder(Rectangle.NO_BORDER);
        cell.setPadding(12);

        PdfPTable band = new PdfPTable(1);
        band.setWidthPercentage(100);
        band.addCell(cell);
        return band;
    }

    // The report title and the three facts a printed report needs: which day, who made it, and when.
    private static void addHeading(Document document, DailyReport report, User user) throws DocumentException {
        Paragraph title = new Paragraph("Daily Pool Usage & Guest Report", TITLE_FONT);
        title.setSpacingBefore(18);
        title.setSpacingAfter(6);
        document.add(title);

        document.add(infoLine("Report date", report.date()));
        document.add(infoLine("Generated by", user.fullName() + " (" + user.role() + ")"));
        document.add(infoLine("Generated at", LocalDateTime.now().format(STAMP)));
    }

    // One line like "Report date: 2026-10-31" with a bold label.
    private static Paragraph infoLine(String label, String value) {
        Paragraph line = new Paragraph();
        line.add(new Chunk(label + ": ", LABEL_FONT));
        line.add(new Chunk(value, TEXT_FONT));
        return line;
    }

    // The same rows and totals as the screen and the CSV: one row per unit, then a TOTAL row.
    private static PdfPTable usageTable(DailyReport report) {
        PdfPTable table = new PdfPTable(COLUMN_WIDTHS);
        table.setWidthPercentage(100);
        table.setSpacingBefore(14);
        table.setHeaderRows(1); // the header row is repeated on every page of a long report

        for (String name : COLUMNS) {
            table.addCell(cell(name, HEADER_FONT, Element.ALIGN_CENTER, WATER_BLUE));
        }

        List<UnitUsage> rows = report.rows();
        for (int i = 0; i < rows.size(); i++) {
            Color shade = (i % 2 == 1) ? STRIPE : null; // light stripes make a long table easier to follow
            addUsageRow(table, rows.get(i), shade);
        }

        addTotalsRow(table, report);
        return table;
    }

    private static void addUsageRow(PdfPTable table, UnitUsage row, Color shade) {
        table.addCell(cell(String.valueOf(row.unitNumber()), TEXT_FONT, Element.ALIGN_CENTER, shade));
        table.addCell(cell(row.ownerName(), TEXT_FONT, Element.ALIGN_LEFT, shade));
        table.addCell(cell(String.valueOf(row.checkIns()), TEXT_FONT, Element.ALIGN_CENTER, shade));
        table.addCell(cell(String.valueOf(row.residents()), TEXT_FONT, Element.ALIGN_CENTER, shade));
        table.addCell(cell(String.valueOf(row.guests()), TEXT_FONT, Element.ALIGN_CENTER, shade));
        table.addCell(cell(String.valueOf(row.total()), TEXT_FONT, Element.ALIGN_CENTER, shade));
    }

    // The TOTAL label spans the Unit and Owner columns, so there is no empty cell in the row.
    private static void addTotalsRow(PdfPTable table, DailyReport report) {
        PdfPCell label = cell("TOTAL", LABEL_FONT, Element.ALIGN_LEFT, LIGHT_BLUE);
        label.setColspan(2);
        table.addCell(label);

        table.addCell(cell(String.valueOf(report.totalCheckIns()), LABEL_FONT, Element.ALIGN_CENTER, LIGHT_BLUE));
        table.addCell(cell(String.valueOf(report.totalResidents()), LABEL_FONT, Element.ALIGN_CENTER, LIGHT_BLUE));
        table.addCell(cell(String.valueOf(report.totalGuests()), LABEL_FONT, Element.ALIGN_CENTER, LIGHT_BLUE));
        table.addCell(cell(String.valueOf(report.totalSwimmers()), LABEL_FONT, Element.ALIGN_CENTER, LIGHT_BLUE));
    }

    // One table cell with the look every cell shares. A null background means "no fill" (plain white).
    private static PdfPCell cell(String text, Font font, int alignment, Color background) {
        PdfPCell cell = new PdfPCell(new Phrase(text, font));
        cell.setHorizontalAlignment(alignment);
        cell.setVerticalAlignment(Element.ALIGN_MIDDLE);
        cell.setPadding(6);
        cell.setBorderColor(LINE_GRAY);
        if (background != null) {
            cell.setBackgroundColor(background);
        }
        return cell;
    }

    // The same sentence the screen shows under the table, so a reader of the printout knows the rule.
    private static Paragraph note() {
        Paragraph note = new Paragraph("A group counts on the day it checked in.", SMALL_FONT);
        note.setSpacingBefore(8);
        return note;
    }

    // ------------------------------------------------------------- shared

    // reports/daily-pool-report-yyyy-MM-dd.<extension>. One place for the name, so the CSV and the PDF
    // of the same day always match.
    private static Path reportFile(DailyReport report, String extension) {
        return REPORTS_FOLDER.resolve("daily-pool-report-" + report.date() + "." + extension);
    }
}
